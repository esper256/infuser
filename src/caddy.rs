use crate::{config::Config, store::State};
use anyhow::{Result, ensure};

/// Generate routing from an initialized catalog. Caddy never receives the control token.
pub fn render(config: &Config, state: &State, wildcard: bool) -> Result<String> {
    config.validate()?;
    let domain = &config.controller.domain;
    let mut out =
        String::from("# Generated by infuser render-caddy. Validate before reloading.\n\n");
    if wildcard {
        out += &format!(
            "*.{domain} {{\n    tls {{\n        dns porkbun {{\n            api_key {{env.PORKBUN_API_KEY}}\n            api_secret_key {{env.PORKBUN_API_SECRET_KEY}}\n        }}\n    }}\n    respond 404\n}}\n\n"
        );
    }
    out += &format!(
        "(members_only) {{\n    forward_auth 127.0.0.1:4180 {{\n        uri /oauth2/auth\n    }}\n}}\n\n{domain} {{\n    handle /oauth2/* {{\n        reverse_proxy 127.0.0.1:4180\n    }}\n    handle {{\n        import members_only\n        respond \"Infuser infrastructure is ready.\"\n    }}\n}}\n\n"
    );
    for (id, site) in &config.sites {
        out += &format!(
            "{id}.{domain} {{\n    route {{\n        import members_only\n        root * \"{}\"\n        encode zstd gzip\n        header Cache-Control \"no-cache\"\n",
            site.root.display()
        );
        if site.cross_origin_isolation {
            out += "        header Cross-Origin-Opener-Policy same-origin\n        header Cross-Origin-Embedder-Policy require-corp\n";
        }
        if site.spa {
            // Missing JS/WASM/assets must remain 404; only document navigation falls back.
            out += "        @navigation {\n            method GET HEAD\n            header Accept *text/html*\n            not path *.*\n            file {path} /index.html\n        }\n        rewrite @navigation {file_match.relative}\n";
        }
        out += "        file_server {\n            precompressed br gzip\n        }\n    }\n}\n\n";
    }
    for (id, game) in &config.games {
        if !game.web {
            continue;
        }
        let instance = state
            .games
            .get(id)
            .ok_or_else(|| anyhow::anyhow!("initialize the catalog before rendering routes"))?;
        ensure!(
            instance.spec == *game,
            "catalog differs from persisted state; initialize/restart first"
        );
        out += &format!(
            "{id}-server.{domain} {{\n    route {{\n        import members_only\n        reverse_proxy 127.0.0.1:{} {{\n            header_up -Cookie\n        }}\n    }}\n}}\n\n",
            instance.port
        );
    }
    Ok(out)
}
